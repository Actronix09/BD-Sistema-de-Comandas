-- =====================================================================
--  7. ATRIBUTOS DERIVADOS
--     No se guardan: cambian cada vez que cambia el dato del que salen,
--     y guardarlos obligaría a mantener la copia sincronizada. Se exponen
--     en vistas. El Folio de Cuenta es la excepción: sale solo de la
--     propia fila y nunca cambia, así que va como columna generada.
-- =====================================================================

-- Evento: Número de mesas.
CREATE VIEW v_evento AS
SELECT e.*,
       (SELECT COUNT(*) FROM mesa m WHERE m.numero_evento = e.numero_evento) AS numero_mesas
FROM evento e;

-- Cuenta: Total acumulado = suma de sus comandas no canceladas.
CREATE VIEW v_cuenta AS
SELECT c.*,
       COALESCE((SELECT SUM(co.precio_cobrado)
                 FROM comanda co
                 WHERE co.numero_evento = c.numero_evento
                   AND co.secuencial    = c.secuencial
                   AND co.estado       <> 'cancelada'), 0)::NUMERIC(10,2) AS total_acumulado
FROM cuenta c;

-- Usuario: Edad.
CREATE VIEW v_usuario AS
SELECT u.id_usuario, u.nombre, u.usuario, u.fecha_nacimiento,
       u.fecha_nacimiento_dia, u.fecha_nacimiento_mes, u.fecha_nacimiento_anio,
       u.rol,
       EXTRACT(YEAR FROM age(CURRENT_DATE, u.fecha_nacimiento))::SMALLINT AS edad
FROM usuario u;

-- Mesero: Propinas acumuladas.
CREATE VIEW v_mesero AS
SELECT m.id_usuario, u.nombre, m.turno_asignado,
       COALESCE((SELECT SUM(p.monto_propina)
                 FROM pago p
                 WHERE p.id_mesero_propina = m.id_usuario), 0)::NUMERIC(10,2) AS propinas_acumuladas
FROM mesero m
JOIN usuario u ON u.id_usuario = m.id_usuario;

-- Producto: Disponible = todos los ingredientes de su receta alcanzan para
-- una porción. Cambia con cada comanda preparada y con cada resurtido.
CREATE VIEW v_producto AS
SELECT p.*,
       NOT EXISTS (SELECT 1
                   FROM receta r
                   JOIN ingrediente i ON i.id_ingrediente = r.id_ingrediente
                   WHERE r.id_producto = p.id_producto
                     AND i.stock_actual < r.cantidad_por_porcion) AS disponible
FROM producto p;

-- Comanda: Precio (el vigente en el catálogo, para compararlo con el cobrado).
CREATE VIEW v_comanda AS
SELECT co.*, p.precio AS precio_catalogo
FROM comanda co
JOIN producto p ON p.id_producto = co.id_producto;

