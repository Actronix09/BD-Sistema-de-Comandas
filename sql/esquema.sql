-- =====================================================================
--  esquema.sql — Sistema de Comandas Profesional
--  Práctica 3: Modelo relacional · Bases de Datos (3CV4)
--
--  Transformación del modelo EER de la Práctica 2
--  (docs/ModeloEntidadRelaciónExtendido.md) a tablas de PostgreSQL 16.
--
--  Se ejecuta sobre una base de datos vacía:
--      psql -v ON_ERROR_STOP=1 -U pg-practica1 -d comandas -f sql/esquema.sql
--
--  Todo va dentro de una transacción: si una instrucción falla, no se
--  crea nada y la base queda vacía otra vez.
--
--  Cada tabla indica en su encabezado la regla de transformación que la
--  origina (Reglas 1 a 9, docs/ReglasDeTransformacion.md).
-- =====================================================================

BEGIN;

-- =====================================================================
--  1. EVENTO y su atributo multivaluado
-- =====================================================================

-- Regla 1 (entidad fuerte) + Regla 2 (atributo compuesto Fecha).
-- La fecha se guarda como DATE y sus componentes Día, Mes y Año se
-- exponen como columnas generadas: hay una columna por componente, como
-- pide la Regla 2, pero no pueden contradecir a la fecha ni formar una
-- fecha imposible (31 de febrero).
CREATE TABLE evento (
    numero_evento      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    fecha              DATE         NOT NULL,
    fecha_dia          SMALLINT     GENERATED ALWAYS AS (EXTRACT(DAY   FROM fecha)::SMALLINT) STORED,
    fecha_mes          SMALLINT     GENERATED ALWAYS AS (EXTRACT(MONTH FROM fecha)::SMALLINT) STORED,
    fecha_anio         SMALLINT     GENERATED ALWAYS AS (EXTRACT(YEAR  FROM fecha)::SMALLINT) STORED,
    tipo_evento        VARCHAR(40)  NOT NULL,
    numero_asistentes  INTEGER      NOT NULL,
    estado             VARCHAR(12)  NOT NULL DEFAULT 'programado',
    CONSTRAINT pk_evento PRIMARY KEY (numero_evento),
    CONSTRAINT ck_evento_asistentes CHECK (numero_asistentes > 0),
    CONSTRAINT ck_evento_estado CHECK (estado IN ('programado', 'en_curso', 'finalizado', 'cancelado'))
);

-- Regla 3: Organizador/cliente es multivaluado.
CREATE TABLE evento_organizador (
    numero_evento  INTEGER       NOT NULL,
    organizador    VARCHAR(120)  NOT NULL,
    CONSTRAINT pk_evento_organizador PRIMARY KEY (numero_evento, organizador),
    CONSTRAINT fk_evento_organizador_evento FOREIGN KEY (numero_evento)
        REFERENCES evento (numero_evento)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- =====================================================================
--  2. JERARQUÍA DE USUARIO (Regla 9, estrategia A: supertipo y subtipos)
--     Disjunta y total. El discriminador `rol` vive en el supertipo y se
--     repite en cada subtipo fijado por CHECK; la clave foránea compuesta
--     (id_usuario, rol) impide que un usuario aparezca en dos subtipos.
-- =====================================================================

-- Regla 1 + Regla 2 (Fecha de nacimiento compuesta) + discriminador.
CREATE TABLE usuario (
    id_usuario            INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    nombre                VARCHAR(120)  NOT NULL,
    usuario               VARCHAR(40)   NOT NULL,
    fecha_nacimiento      DATE          NOT NULL,
    fecha_nacimiento_dia  SMALLINT      GENERATED ALWAYS AS (EXTRACT(DAY   FROM fecha_nacimiento)::SMALLINT) STORED,
    fecha_nacimiento_mes  SMALLINT      GENERATED ALWAYS AS (EXTRACT(MONTH FROM fecha_nacimiento)::SMALLINT) STORED,
    fecha_nacimiento_anio SMALLINT      GENERATED ALWAYS AS (EXTRACT(YEAR  FROM fecha_nacimiento)::SMALLINT) STORED,
    contrasena_hash       VARCHAR(255)  NOT NULL,
    rol                   VARCHAR(12)   NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_usuario UNIQUE (usuario),
    CONSTRAINT uq_usuario_id_rol UNIQUE (id_usuario, rol),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('mesero', 'bar_cocina', 'cajero_admin')),
    CONSTRAINT ck_usuario_nacimiento CHECK (fecha_nacimiento >= DATE '1900-01-01')
);

CREATE TABLE mesero (
    id_usuario      INTEGER      NOT NULL,
    rol             VARCHAR(12)  NOT NULL DEFAULT 'mesero',
    turno_asignado  VARCHAR(12)  NOT NULL,
    CONSTRAINT pk_mesero PRIMARY KEY (id_usuario),
    CONSTRAINT ck_mesero_rol CHECK (rol = 'mesero'),
    CONSTRAINT ck_mesero_turno CHECK (turno_asignado IN ('matutino', 'vespertino', 'nocturno')),
    CONSTRAINT fk_mesero_usuario FOREIGN KEY (id_usuario, rol)
        REFERENCES usuario (id_usuario, rol)
        ON DELETE CASCADE
        ON UPDATE RESTRICT
);

CREATE TABLE bar_cocina (
    id_usuario         INTEGER      NOT NULL,
    rol                VARCHAR(12)  NOT NULL DEFAULT 'bar_cocina',
    estado             VARCHAR(10)  NOT NULL DEFAULT 'desocupado',
    estacion_asignada  VARCHAR(6)   NOT NULL,
    CONSTRAINT pk_bar_cocina PRIMARY KEY (id_usuario),
    CONSTRAINT ck_bar_cocina_rol CHECK (rol = 'bar_cocina'),
    CONSTRAINT ck_bar_cocina_estado CHECK (estado IN ('ocupado', 'desocupado')),
    CONSTRAINT ck_bar_cocina_estacion CHECK (estacion_asignada IN ('bar', 'cocina')),
    CONSTRAINT fk_bar_cocina_usuario FOREIGN KEY (id_usuario, rol)
        REFERENCES usuario (id_usuario, rol)
        ON DELETE CASCADE
        ON UPDATE RESTRICT
);

CREATE TABLE cajero_admin (
    id_usuario     INTEGER      NOT NULL,
    rol            VARCHAR(12)  NOT NULL DEFAULT 'cajero_admin',
    nivel_acceso   VARCHAR(13)  NOT NULL DEFAULT 'cajero',
    caja_asignada  SMALLINT     NOT NULL,
    CONSTRAINT pk_cajero_admin PRIMARY KEY (id_usuario),
    CONSTRAINT ck_cajero_admin_rol CHECK (rol = 'cajero_admin'),
    CONSTRAINT ck_cajero_admin_nivel CHECK (nivel_acceso IN ('cajero', 'administrador')),
    CONSTRAINT ck_cajero_admin_caja CHECK (caja_asignada > 0),
    CONSTRAINT fk_cajero_admin_usuario FOREIGN KEY (id_usuario, rol)
        REFERENCES usuario (id_usuario, rol)
        ON DELETE CASCADE
        ON UPDATE RESTRICT
);

-- Completitud total: todo usuario debe tener su fila en el subtipo que
-- indica su rol. No se puede expresar con CHECK ni con claves foráneas
-- (sería una referencia circular), así que se verifica al confirmar la
-- transacción con disparadores de restricción diferidos.
CREATE FUNCTION verificar_especializacion_total() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_id   INTEGER := CASE WHEN TG_OP = 'DELETE' THEN OLD.id_usuario ELSE NEW.id_usuario END;
    v_rol  VARCHAR(12);
BEGIN
    SELECT rol INTO v_rol FROM usuario WHERE id_usuario = v_id;
    IF NOT FOUND THEN
        RETURN NULL;  -- el usuario ya no existe: no hay nada que verificar
    END IF;

    IF (v_rol = 'mesero'       AND NOT EXISTS (SELECT 1 FROM mesero       WHERE id_usuario = v_id))
    OR (v_rol = 'bar_cocina'   AND NOT EXISTS (SELECT 1 FROM bar_cocina   WHERE id_usuario = v_id))
    OR (v_rol = 'cajero_admin' AND NOT EXISTS (SELECT 1 FROM cajero_admin WHERE id_usuario = v_id))
    THEN
        RAISE EXCEPTION 'el usuario % tiene rol "%" pero no tiene fila en ese subtipo', v_id, v_rol
            USING ERRCODE = 'check_violation',
                  HINT    = 'La especialización de Usuario es total: inserte también la fila del subtipo en la misma transacción.';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER ct_usuario_total
    AFTER INSERT ON usuario
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION verificar_especializacion_total();

CREATE CONSTRAINT TRIGGER ct_mesero_total
    AFTER DELETE ON mesero
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION verificar_especializacion_total();

CREATE CONSTRAINT TRIGGER ct_bar_cocina_total
    AFTER DELETE ON bar_cocina
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION verificar_especializacion_total();

CREATE CONSTRAINT TRIGGER ct_cajero_admin_total
    AFTER DELETE ON cajero_admin
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION verificar_especializacion_total();

-- =====================================================================
--  3. ENTIDADES DÉBILES (Regla 8, dependencia de identificación)
-- =====================================================================

-- Mesa depende de Evento por *Pertenece*. Clave: (numero_evento, numero_mesa).
-- Además recibe por Regla 4 la clave del mesero que la atiende (*Atiende*,
-- mínimo 1 del lado de la mesa → NOT NULL).
CREATE TABLE mesa (
    numero_evento  INTEGER   NOT NULL,
    numero_mesa    SMALLINT  NOT NULL,
    id_mesero      INTEGER   NOT NULL,
    CONSTRAINT pk_mesa PRIMARY KEY (numero_evento, numero_mesa),
    CONSTRAINT ck_mesa_numero CHECK (numero_mesa > 0),
    CONSTRAINT fk_mesa_evento FOREIGN KEY (numero_evento)
        REFERENCES evento (numero_evento)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_mesa_mesero FOREIGN KEY (id_mesero)
        REFERENCES mesero (id_usuario)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

-- Cuenta depende de Evento por *Abre*. Clave: (numero_evento, secuencial).
-- La relación *Tiene* (mesa donde se abrió, mínimo 1) se propaga por
-- Regla 4 como clave foránea compuesta hacia mesa, que comparte
-- numero_evento: así la cuenta no puede quedar en una mesa de otro evento.
-- El Folio es derivado de la clave y se guarda como columna generada.
CREATE TABLE cuenta (
    numero_evento  INTEGER      NOT NULL,
    secuencial     SMALLINT     NOT NULL,
    numero_mesa    SMALLINT     NOT NULL,
    nombre         VARCHAR(60)  NOT NULL,
    folio          VARCHAR(30)  GENERATED ALWAYS AS (
                       numero_evento::TEXT || '-' || numero_mesa::TEXT || '-' || secuencial::TEXT
                   ) STORED,
    estado         VARCHAR(8)   NOT NULL DEFAULT 'abierta',
    CONSTRAINT pk_cuenta PRIMARY KEY (numero_evento, secuencial),
    CONSTRAINT ck_cuenta_secuencial CHECK (secuencial > 0),
    CONSTRAINT ck_cuenta_estado CHECK (estado IN ('abierta', 'cerrada')),
    CONSTRAINT ck_cuenta_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT fk_cuenta_evento FOREIGN KEY (numero_evento)
        REFERENCES evento (numero_evento)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_cuenta_mesa FOREIGN KEY (numero_evento, numero_mesa)
        REFERENCES mesa (numero_evento, numero_mesa)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

-- =====================================================================
--  4. CATÁLOGO: PRODUCTO, INVENTARIO, PAQUETE Y SUS RELACIONES
-- =====================================================================

-- Regla 1. La relación recursiva *Variante* (0,N):(0,1) se resuelve con
-- Regla 4 dentro de la misma tabla: la variante apunta a su principal.
CREATE TABLE producto (
    id_producto            INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    nombre                 VARCHAR(80)    NOT NULL,
    descripcion            VARCHAR(255)   NULL,
    categoria              VARCHAR(10)    NOT NULL,
    precio                 NUMERIC(10,2)  NOT NULL,
    id_producto_principal  INTEGER        NULL,
    CONSTRAINT pk_producto PRIMARY KEY (id_producto),
    CONSTRAINT uq_producto_nombre UNIQUE (nombre),
    CONSTRAINT ck_producto_categoria CHECK (categoria IN ('alimentos', 'bebidas', 'dulceria')),
    CONSTRAINT ck_producto_precio CHECK (precio >= 0),
    CONSTRAINT ck_producto_no_autovariante CHECK (id_producto_principal <> id_producto),
    CONSTRAINT fk_producto_principal FOREIGN KEY (id_producto_principal)
        REFERENCES producto (id_producto)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

-- "Una variante no puede tener más variantes": la jerarquía de variantes
-- tiene un solo nivel. Depende de otra fila, así que no cabe en un CHECK.
CREATE FUNCTION verificar_variante_un_nivel() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.id_producto_principal IS NULL THEN
        RETURN NEW;
    END IF;
    IF EXISTS (SELECT 1 FROM producto
               WHERE id_producto = NEW.id_producto_principal
                 AND id_producto_principal IS NOT NULL) THEN
        RAISE EXCEPTION 'el producto % es una variante y no puede tener variantes', NEW.id_producto_principal
            USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM producto WHERE id_producto_principal = NEW.id_producto) THEN
        RAISE EXCEPTION 'el producto % tiene variantes y no puede volverse variante de otro', NEW.id_producto
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_producto_variante
    BEFORE INSERT OR UPDATE OF id_producto_principal ON producto
    FOR EACH ROW EXECUTE FUNCTION verificar_variante_un_nivel();

-- Regla 1. Ingrediente dejó de ser un atributo multivaluado de Producto:
-- tiene datos propios (stock y unidad) y un mismo ingrediente se comparte
-- entre muchos productos, así que es una entidad con un solo stock.
-- Las cantidades se guardan en la unidad base del ingrediente (gramos,
-- mililitros o piezas), por eso NUMERIC con tres decimales.
CREATE TABLE ingrediente (
    id_ingrediente  INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(60)    NOT NULL,
    unidad_medida   VARCHAR(5)     NOT NULL,
    stock_actual    NUMERIC(10,3)  NOT NULL DEFAULT 0,
    stock_minimo    NUMERIC(10,3)  NOT NULL DEFAULT 0,
    CONSTRAINT pk_ingrediente PRIMARY KEY (id_ingrediente),
    CONSTRAINT uq_ingrediente_nombre UNIQUE (nombre),
    CONSTRAINT ck_ingrediente_unidad CHECK (unidad_medida IN ('g', 'ml', 'pieza')),
    CONSTRAINT ck_ingrediente_stock CHECK (stock_actual >= 0),
    CONSTRAINT ck_ingrediente_minimo CHECK (stock_minimo >= 0)
);

-- Regla 5: *Receta* es muchos a muchos (Producto–Ingrediente) con el
-- atributo propio Cantidad por porción. La receta es parte del producto
-- (se borra con él); un ingrediente no se puede borrar mientras alguna
-- receta lo use.
CREATE TABLE receta (
    id_producto           INTEGER        NOT NULL,
    id_ingrediente        INTEGER        NOT NULL,
    cantidad_por_porcion  NUMERIC(10,3)  NOT NULL,
    CONSTRAINT pk_receta PRIMARY KEY (id_producto, id_ingrediente),
    CONSTRAINT ck_receta_cantidad CHECK (cantidad_por_porcion > 0),
    CONSTRAINT fk_receta_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_receta_ingrediente FOREIGN KEY (id_ingrediente)
        REFERENCES ingrediente (id_ingrediente)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Regla 1.
CREATE TABLE paquete (
    numero_paquete  INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    monto           NUMERIC(10,2)  NOT NULL,
    detalles        VARCHAR(255)   NOT NULL,
    CONSTRAINT pk_paquete PRIMARY KEY (numero_paquete),
    CONSTRAINT ck_paquete_monto CHECK (monto >= 0)
);

-- Regla 5: *Incluye* es muchos a muchos (contenido base del catálogo).
CREATE TABLE paquete_producto (
    numero_paquete  INTEGER  NOT NULL,
    id_producto     INTEGER  NOT NULL,
    CONSTRAINT pk_paquete_producto PRIMARY KEY (numero_paquete, id_producto),
    CONSTRAINT fk_paquete_producto_paquete FOREIGN KEY (numero_paquete)
        REFERENCES paquete (numero_paquete)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_paquete_producto_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Regla 7: *Acuerda* es ternaria (Evento, Paquete, Producto) con el
-- atributo propio Cantidad acordada. No se exige que el par
-- (paquete, producto) exista en paquete_producto: el catálogo es una base,
-- no una lista cerrada.
CREATE TABLE acuerdo (
    numero_evento      INTEGER  NOT NULL,
    numero_paquete     INTEGER  NOT NULL,
    id_producto        INTEGER  NOT NULL,
    cantidad_acordada  INTEGER  NOT NULL,
    CONSTRAINT pk_acuerdo PRIMARY KEY (numero_evento, numero_paquete, id_producto),
    CONSTRAINT ck_acuerdo_cantidad CHECK (cantidad_acordada > 0),
    CONSTRAINT fk_acuerdo_evento FOREIGN KEY (numero_evento)
        REFERENCES evento (numero_evento)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_acuerdo_paquete FOREIGN KEY (numero_paquete)
        REFERENCES paquete (numero_paquete)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_acuerdo_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- =====================================================================
--  5. OPERACIÓN: COMANDA, PAGO Y ANTICIPO
-- =====================================================================

-- Regla 1 + Regla 2 (Time Stamp compuesto) + cinco relaciones 1:N por
-- Regla 4:
--   *Genera*     cuenta → comanda        (1,1) → NOT NULL
--   *Levanta*    mesero → comanda        (1,1) → NOT NULL
--   *Referencia* producto → comanda      (1,1) → NOT NULL
--   *Prepara*    bar_cocina → comanda    (0,1) → admite NULL
--   *Cancela*    cajero_admin → comanda  (0,1) → admite NULL
CREATE TABLE comanda (
    id_comanda         INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    fecha_hora         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    fecha_hora_dia     SMALLINT       GENERATED ALWAYS AS (EXTRACT(DAY   FROM fecha_hora AT TIME ZONE 'America/Mexico_City')::SMALLINT) STORED,
    fecha_hora_mes     SMALLINT       GENERATED ALWAYS AS (EXTRACT(MONTH FROM fecha_hora AT TIME ZONE 'America/Mexico_City')::SMALLINT) STORED,
    fecha_hora_anio    SMALLINT       GENERATED ALWAYS AS (EXTRACT(YEAR  FROM fecha_hora AT TIME ZONE 'America/Mexico_City')::SMALLINT) STORED,
    fecha_hora_hora    TIME           GENERATED ALWAYS AS ((fecha_hora AT TIME ZONE 'America/Mexico_City')::TIME(0)) STORED,
    precio_cobrado     NUMERIC(10,2)  NOT NULL,
    estado             VARCHAR(14)    NOT NULL DEFAULT 'pendiente',
    detalles           VARCHAR(255)   NULL,
    numero_evento      INTEGER        NOT NULL,
    secuencial         SMALLINT       NOT NULL,
    id_mesero          INTEGER        NOT NULL,
    id_producto        INTEGER        NOT NULL,
    id_bar_cocina      INTEGER        NULL,
    id_cajero_cancela  INTEGER        NULL,
    CONSTRAINT pk_comanda PRIMARY KEY (id_comanda),
    CONSTRAINT ck_comanda_precio CHECK (precio_cobrado >= 0),
    CONSTRAINT ck_comanda_estado CHECK (estado IN ('pendiente', 'en_preparacion', 'lista', 'entregada', 'cancelada')),
    -- Solo está cancelada si un cajero/administrador la canceló, y viceversa.
    CONSTRAINT ck_comanda_cancelacion CHECK ((estado = 'cancelada') = (id_cajero_cancela IS NOT NULL)),
    -- Sin estación solo si sigue pendiente o se canceló antes de prepararse.
    CONSTRAINT ck_comanda_preparacion CHECK (id_bar_cocina IS NOT NULL OR estado IN ('pendiente', 'cancelada')),
    CONSTRAINT fk_comanda_cuenta FOREIGN KEY (numero_evento, secuencial)
        REFERENCES cuenta (numero_evento, secuencial)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_comanda_mesero FOREIGN KEY (id_mesero)
        REFERENCES mesero (id_usuario)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,
    CONSTRAINT fk_comanda_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_comanda_bar_cocina FOREIGN KEY (id_bar_cocina)
        REFERENCES bar_cocina (id_usuario)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,
    CONSTRAINT fk_comanda_cajero_cancela FOREIGN KEY (id_cajero_cancela)
        REFERENCES cajero_admin (id_usuario)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

-- "El Precio cobrado se copia del producto al levantar la comanda y ya
-- no cambia aunque suba el catálogo": si no se indica, se toma el precio
-- vigente; una vez guardado no se puede modificar.
CREATE FUNCTION fijar_precio_cobrado() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.precio_cobrado IS NULL THEN
            SELECT precio INTO NEW.precio_cobrado FROM producto WHERE id_producto = NEW.id_producto;
        END IF;
    ELSIF NEW.precio_cobrado IS DISTINCT FROM OLD.precio_cobrado THEN
        RAISE EXCEPTION 'el precio cobrado de la comanda % ya quedó fijado y no se puede modificar', OLD.id_comanda
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_comanda_precio
    BEFORE INSERT OR UPDATE OF precio_cobrado ON comanda
    FOR EACH ROW EXECUTE FUNCTION fijar_precio_cobrado();

-- "Al preparar una comanda se descuenta del stock de cada ingrediente la
-- cantidad de la receta, y el stock nunca queda negativo". El consumo
-- ocurre una sola vez: cuando la comanda entra a preparación (o se
-- registra ya preparada). Una comanda cancelada mientras estaba pendiente
-- no consumió nada; una cancelada después de prepararse ya gastó sus
-- ingredientes y no los devuelve. Si algún ingrediente no alcanza para
-- una porción, la comanda no puede pasar a preparación.
CREATE FUNCTION descontar_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    faltante  RECORD;
BEGIN
    IF NEW.estado NOT IN ('en_preparacion', 'lista', 'entregada') THEN
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.estado IN ('en_preparacion', 'lista', 'entregada') THEN
        RETURN NEW;
    END IF;

    SELECT i.nombre, i.stock_actual, i.unidad_medida, r.cantidad_por_porcion
      INTO faltante
      FROM receta r
      JOIN ingrediente i ON i.id_ingrediente = r.id_ingrediente
     WHERE r.id_producto = NEW.id_producto
       AND i.stock_actual < r.cantidad_por_porcion
     LIMIT 1;
    -- El CHECK ck_ingrediente_stock respalda esta revisión si dos comandas
    -- compiten por el mismo ingrediente al mismo tiempo.
    IF FOUND THEN
        RAISE EXCEPTION 'no hay stock suficiente de "%" para preparar la comanda (quedan % %, la receta pide %)',
                        faltante.nombre, faltante.stock_actual, faltante.unidad_medida, faltante.cantidad_por_porcion
            USING ERRCODE = 'check_violation',
                  HINT = 'Resurta el ingrediente o cancele la comanda.';
    END IF;

    UPDATE ingrediente i
       SET stock_actual = i.stock_actual - r.cantidad_por_porcion
      FROM receta r
     WHERE r.id_ingrediente = i.id_ingrediente
       AND r.id_producto = NEW.id_producto;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_comanda_stock
    AFTER INSERT OR UPDATE OF estado ON comanda
    FOR EACH ROW EXECUTE FUNCTION descontar_stock();

-- Regla 1 + Regla 2 (Time Stamp) + tres relaciones 1:N por Regla 4:
--   *Recibe*         cuenta → pago        (1,1) → NOT NULL
--   *Maneja*         cajero_admin → pago  (1,1) → NOT NULL
--   *Recibe propina* mesero → pago        (0,1) → admite NULL, y su
--                    atributo de relación Monto de propina viaja con ella.
CREATE TABLE pago (
    numero_pago        INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    monto              NUMERIC(10,2)  NOT NULL,
    forma_pago         VARCHAR(13)    NOT NULL,
    fecha_hora         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    fecha_hora_dia     SMALLINT       GENERATED ALWAYS AS (EXTRACT(DAY   FROM fecha_hora AT TIME ZONE 'America/Mexico_City')::SMALLINT) STORED,
    fecha_hora_mes     SMALLINT       GENERATED ALWAYS AS (EXTRACT(MONTH FROM fecha_hora AT TIME ZONE 'America/Mexico_City')::SMALLINT) STORED,
    fecha_hora_anio    SMALLINT       GENERATED ALWAYS AS (EXTRACT(YEAR  FROM fecha_hora AT TIME ZONE 'America/Mexico_City')::SMALLINT) STORED,
    fecha_hora_hora    TIME           GENERATED ALWAYS AS ((fecha_hora AT TIME ZONE 'America/Mexico_City')::TIME(0)) STORED,
    numero_evento      INTEGER        NOT NULL,
    secuencial         SMALLINT       NOT NULL,
    id_cajero          INTEGER        NOT NULL,
    id_mesero_propina  INTEGER        NULL,
    monto_propina      NUMERIC(10,2)  NULL,
    CONSTRAINT pk_pago PRIMARY KEY (numero_pago),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT ck_pago_forma CHECK (forma_pago IN ('efectivo', 'tarjeta', 'transferencia')),
    -- La propina va completa o no va: mesero y monto aparecen juntos.
    CONSTRAINT ck_pago_propina_completa CHECK ((id_mesero_propina IS NULL) = (monto_propina IS NULL)),
    CONSTRAINT ck_pago_propina_monto CHECK (monto_propina IS NULL OR monto_propina >= 0),
    CONSTRAINT fk_pago_cuenta FOREIGN KEY (numero_evento, secuencial)
        REFERENCES cuenta (numero_evento, secuencial)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_pago_cajero FOREIGN KEY (id_cajero)
        REFERENCES cajero_admin (id_usuario)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,
    CONSTRAINT fk_pago_mesero_propina FOREIGN KEY (id_mesero_propina)
        REFERENCES mesero (id_usuario)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

-- Regla 1 + Regla 2 (Fecha) + Regla 4 (*Recibe*: evento → anticipo, (1,1)).
CREATE TABLE anticipo (
    id_anticipo    INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    monto          NUMERIC(10,2)  NOT NULL,
    fecha          DATE           NOT NULL DEFAULT CURRENT_DATE,
    fecha_dia      SMALLINT       GENERATED ALWAYS AS (EXTRACT(DAY   FROM fecha)::SMALLINT) STORED,
    fecha_mes      SMALLINT       GENERATED ALWAYS AS (EXTRACT(MONTH FROM fecha)::SMALLINT) STORED,
    fecha_anio     SMALLINT       GENERATED ALWAYS AS (EXTRACT(YEAR  FROM fecha)::SMALLINT) STORED,
    numero_evento  INTEGER        NOT NULL,
    CONSTRAINT pk_anticipo PRIMARY KEY (id_anticipo),
    CONSTRAINT ck_anticipo_monto CHECK (monto > 0),
    CONSTRAINT fk_anticipo_evento FOREIGN KEY (numero_evento)
